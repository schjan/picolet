// Package sops owns everything picolet does with SOPS-encrypted files
// (spec #248): keyless inspection, JSON Pointers, the `.sops.` path rule,
// Podman secret naming, age recipient parsing, checking a file's age
// Recipients against the Fleet-root `.sops.yaml` creation rule
// (ReadCreationRules, CreationRules.Check: upstream's loader over a reduced
// private copy in a temp dir, so it needs a writable TMPDIR), and decryption
// with explicit age identities. It is the only package allowed to import
// github.com/getsops/sops/v3; a depguard rule in .golangci.yml enforces that.
//
// Nothing in the keyless half reads an age identity. Other packages test
// against the committed fixture corpus in testdata/sops (regenerated by
// `task sops:corpus`) instead of encrypting.
//
// The decrypting half (Reader) takes its identities only from
// ParseIdentities: a picolet-owned keyservice unwraps age stanzas with
// upstream's age MasterKey, given those identities explicitly and never an
// empty set, so the MasterKey's ambient-key fallback (SOPS_AGE_KEY*,
// keys.txt, ~/.ssh, commands, plugins) is unreachable and every non-age key
// backend is never consulted. Its errors fall into
// fixed classes (ErrNoIdentity, ErrNotRecipient, ErrEditedOutsideSOPS,
// ErrBadPointer, ErrNotLeaf, ErrNotSOPSPath, ErrNotSOPSFile,
// ErrFileTooLarge) and never carry an upstream error string, a decrypted
// value or a hash of one. A Reader serves one resolve: it decrypts each file
// once, and Scrub removes the values it decrypted from error text that other
// code (template helpers, validators) may have embedded them in.
