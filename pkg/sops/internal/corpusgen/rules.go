// ruleCase is one creation-rule matching case: a Fleet-root .sops.yaml with
// these path_regex values, in order, and the Fleet-relative files to match.
type ruleCase struct {
	Name  string   `json:"name"`
	Rules []string `json:"rules"`
	Files []string `json:"-"`
	// Expected maps each file to the index of the rule `sops` chose, or -1
	// when it found no matching rule.
	Expected map[string]int `json:"expected"`
}

// ruleCases pin the rule choice of `sops` (run from the Fleet root with a
// relative path, as an author does) for pkg/sops' rule matcher.
var ruleCases = []ruleCase{
	{
		Name:  "first-match-wins",
		Rules: []string{`^secrets/`, `\.sops\.yaml$`},
		Files: []string{"secrets/db.sops.yaml", "other/app.sops.yaml", "other/app.sops.json"},
	},
	{
		Name:  "empty-regex-matches-all",
		Rules: []string{`^hosts/`, ``, `^secrets/`},
		Files: []string{"hosts/srv-1/app.sops.yaml", "secrets/db.sops.yaml", "db.sops.env"},
	},
	{
		Name:  "nested-directories",
		Rules: []string{`^services/[^/]+/secrets\.sops\.yaml$`, `secrets/`, `^hosts/srv-1/`},
		Files: []string{
			"services/web/secrets.sops.yaml",
			"services/web/nested/secrets.sops.yaml",
			"hosts/srv-1/secrets/app.sops.yaml",
			"hosts/srv-1/app.sops.yaml",
			"hosts/srv-2/app.sops.yaml",
		},
	},
	{
		Name:  "unanchored",
		Rules: []string{`db`},
		Files: []string{"secrets/db.sops.yaml", "hosts/srv-1/mydb.sops.env", "app.sops.yaml"},
	},
	{
		Name:  "relative-to-fleet-root",
		Rules: []string{`^db\.sops\.yaml$`, `^/`},
		Files: []string{"db.sops.yaml", "secrets/db.sops.yaml"},
	},
}

// writeRuleCases runs every ruleCase through `sops encrypt` and writes the
// rule it chose to creation-rules/expected.json. Each rule gets a fresh
// throwaway recipient; the recipient in the output names the rule.
func writeRuleCases(dir string) error {
	// The cases run outside the module, where `go tool` can't find sops.
	bin, err := exec.Command("go", "tool", "-n", "sops").Output()
	if err != nil {
		return fmt.Errorf("locating the sops tool: %w", err)
	}
	sopsBin := strings.TrimSpace(string(bin))
	cases := make([]ruleCase, 0, len(ruleCases))
	for _, c := range ruleCases {
		expected, err := runRuleCase(sopsBin, c)
		if err != nil {
			return fmt.Errorf("rule case %s: %w", c.Name, err)
		}
		c.Expected = expected
		cases = append(cases, c)
	}
	out, err := json.MarshalIndent(struct {
		Comment string     `json:"_comment"`
		Cases   []ruleCase `json:"cases"`
	}{
		Comment: "Generated by pkg/sops/internal/corpusgen (task sops:corpus): the creation rule `sops` chose per file; -1 is no matching rule.",
		Cases:   cases,
	}, "", "  ")
	if err != nil {
		return fmt.Errorf("encoding rule cases: %w", err)
	}
	outDir := filepath.Join(dir, "creation-rules")
	if err := os.MkdirAll(outDir, 0o750); err != nil {
		return fmt.Errorf("creating %s: %w", outDir, err)
	}
	return os.WriteFile(filepath.Join(outDir, "expected.json"), append(out, '\n'), 0o600)
}

// runRuleCase returns, per file of c, the index of the rule `sops` chose.
func runRuleCase(sopsBin string, c ruleCase) (map[string]int, error) {
	root, err := os.MkdirTemp("", "picolet-sops-rules-")
	if err != nil {
		return nil, fmt.Errorf("creating temp dir: %w", err)
	}
	defer func() { _ = os.RemoveAll(root) }()

	recipients := make([]string, len(c.Rules))
	var cfg strings.Builder
	cfg.WriteString("creation_rules:\n")
	for i, re := range c.Rules {
		id, err := age.GenerateX25519Identity()
		if err != nil {
			return nil, fmt.Errorf("generating recipient: %w", err)
		}
		recipients[i] = id.Recipient().String()
		quoted, err := json.Marshal(re) // a JSON string is a YAML string
		if err != nil {
			return nil, fmt.Errorf("quoting regex: %w", err)
		}
		fmt.Fprintf(&cfg, "  - path_regex: %s\n    age: %s\n", quoted, recipients[i])
	}
	if err := os.WriteFile(filepath.Join(root, ".sops.yaml"), []byte(cfg.String()), 0o600); err != nil {
		return nil, fmt.Errorf("writing .sops.yaml: %w", err)
	}

	expected := map[string]int{}
	for _, file := range c.Files {
		idx, err := ruleChosen(sopsBin, root, file, recipients)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		expected[file] = idx
	}
	return expected, nil
}

// ruleChosen encrypts file (Fleet-relative) from root and returns the index
// of the rule whose recipient the output carries, or -1 when sops found no
// matching rule.
func ruleChosen(sopsBin, root, file string, recipients []string) (int, error) {
	full := filepath.Join(root, filepath.FromSlash(file))
	if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
		return 0, fmt.Errorf("creating parent: %w", err)
	}
	if err := os.WriteFile(full, plainFor(file), 0o600); err != nil {
		return 0, fmt.Errorf("writing plaintext: %w", err)
	}
	cmd := exec.Command(sopsBin, "encrypt", file)
	cmd.Dir = root
	cmd.Env = sopsFreeEnv()
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		if strings.Contains(stderr.String(), "no matching creation rules found") {
			return -1, nil
		}
		return 0, fmt.Errorf("sops encrypt: %w: %s", err, stderr.String())
	}
	found := -1
	for i, r := range recipients {
		if bytes.Contains(stdout.Bytes(), []byte(r)) {
			if found != -1 {
				return 0, errors.New("output carries recipients of two rules")
			}
			found = i
		}
	}
	if found == -1 {
		return 0, errors.New("output carries no rule's recipient")
	}
	return found, nil
}

// plainFor returns a minimal plaintext in the format sops picks for file.
func plainFor(file string) []byte {
	switch path.Ext(file) {
	case ".yaml", ".yml":
		return []byte("k: v\n")
	case ".json":
		return []byte(`{"k": "v"}` + "\n")
	case ".env":
		return []byte("k=v\n")
	default:
		return []byte("v\n")
	}
}
